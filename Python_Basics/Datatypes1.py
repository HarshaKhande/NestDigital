# Numeric - int , float and complex

# Integer (int)

age = 20
print(age)

quantity = 67
print(quantity)

# float - decimal values
price = 67.45
print (price)

PERCCENTAGE = 45.67
print(PERCCENTAGE)

# complex
z = 1 + 3j
print(z)

#sequence - str, list , tuples , range - orrdered set of data

# str - collections of words

name = "John"
print(name)

course = "Squish automation"
print(course)

# list - collections of elements - lists can be changed

language = ["Python" ,"Java", "Perl", "Perl"]
print(language)
print(language[1])

# list of integers
numbers = [3,4,5,8]
print(numbers)
print(numbers[3])

# tuples -  tuples cannot be changed  once it is created

fruits = ("Orange" , "Grapes", "Peech", "Orange")
print(fruits)

# range - start , stop and step  - generate the sequence of numbers

for i in range (5):
    print(i)

for i in range (2,6):
    print(i)

# mapping - unordered set of data - Unordered key-value pairs

# key and value

user = {"id": 1, "name": "John"}
print(user)

credentails = {"username": "admin" , "password": "admin123"}
print(credentails)


# set types - unordered collection of unique elements

setvalues = {1,2,3,3}
print(setvalues)

# boolean - true or false
is_valid = True
print(is_valid)

is_active = False
print(is_active)


# binary - byte data -
number = 10
print(bin(number))


# None - no value present
ordernumber = None
print(ordernumber)















